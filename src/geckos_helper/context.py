"""Builds the short, hand-picked context file describing this machine's tools.

Regenerated by `gecko context` (on a timer, after dnf updates, or on demand), and
combined with the profile system prompt into the file passed to the agent.
"""

import json
import re
import shutil
import subprocess
import sys
import time
import tomllib
from datetime import datetime

from . import paths, profiles
from .config import expand, load_config, load_state

SNAPSHOT = paths.DATA_DIR / "context.json"
ANSI = re.compile(r"\x1b\[[0-9;]*m")


def _find(cmd: str, extra: list[str]) -> str | None:
    for p in extra:
        if expand(p).exists():
            return str(expand(p))
    return shutil.which(cmd)


def installed_tools() -> list[dict]:
    spec = tomllib.loads((paths.PROFILE_DIR / "tools.toml").read_text())
    out = []
    for t in spec["tool"]:
        if t.get("check_config") and not (paths.HOME / ".config/quickshell" / t["check_config"]).exists():
            continue  # a Quickshell config that isn't installed
        if where := _find(t["cmd"], t.get("paths", [])):
            out.append({"name": t["name"], "cmd": where if t.get("paths") else t["cmd"], "use": t["use"]})
    return out


def _mcp_names(argv: list[str]) -> list[str]:
    """Server names from `<agent> mcp list` (formats differ; take the name before ':')."""
    try:
        out = subprocess.run(argv, capture_output=True, text=True, timeout=90,
                             stdin=subprocess.DEVNULL).stdout
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return []
    names = []
    for line in ANSI.sub("", out).splitlines():
        m = re.match(r"^\s*(?:[●○✓✗•*-]\s*)?([\w.@/ -]+?):\s", line)
        if m and not line.lower().startswith(("checking", "warning")):
            names.append(m[1].strip())
    return sorted(set(names))


def agent_mcps() -> dict[str, list[str]]:
    agents = load_config()["agents"]
    claude = str(expand(agents["claude"]["path"]))
    return {"claude": [n for n in _mcp_names([claude, "mcp", "list"]) if n != "gecko"]}


def user_skills() -> list[str]:
    d = paths.HOME / ".claude/skills"
    return sorted(p.parent.name for p in d.glob("*/SKILL.md")) if d.is_dir() else []


NEW_FOR_DAYS = 7


def generate(refresh_mcps: bool = True) -> str:
    """Rebuild the context file. refresh_mcps=False reuses the last MCP list (fast)."""
    paths.ensure_dirs()
    try:
        prev = json.loads(SNAPSHOT.read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        prev = {}
    tools = installed_tools()
    mcps = agent_mcps() if refresh_mcps or "mcps" not in prev else {"claude": prev["mcps"]}
    skills = user_skills()
    state = load_state()
    off = [k for k, on in state["capabilities"].items() if not on]

    # Remember when each item first appeared, to point out new ones for a week.
    now = {"tools": [t["name"] for t in tools], "mcps": mcps.get("claude", []), "skills": skills}
    first_seen: dict[str, float] = prev.get("first_seen", {})
    baseline = not first_seen
    ts = time.time()
    for kind, names in now.items():
        for n in names:
            first_seen.setdefault(f"{kind[:-1]} `{n}`", 0 if baseline else ts)
    new = [k for k, t in first_seen.items() if t and ts - t < NEW_FOR_DAYS * 86400]

    lines = [f"_Context generated {datetime.now():%Y-%m-%d %H:%M}._", "", "### Command-line tools"]
    lines += [f"- **{t['name']}** (`{t['cmd']}`): {t['use']}" for t in tools]
    if mcps.get("claude"):
        lines += ["", "### MCP servers (Claude)", ", ".join(mcps["claude"])]
    if skills:
        lines += ["", "### Your own skills (Claude)", _group(skills)]
    lines += ["", "### Gecko desktop capabilities"]
    lines.append("All enabled." if not off else "Turned off by the user: " + ", ".join(off) +
                 ". Don't try to work around a disabled capability.")
    if new:
        lines += ["", "### New this week", ", ".join(new)]
    lines += ["", "Desktop: end-4 illogical-impulse on Hyprland. Obsidian vault: "
              f"`{load_config()['desktop']['obsidian_vault']}`."]
    text = "\n".join(lines) + "\n"

    paths.CONTEXT_FILE.write_text(text)
    SNAPSHOT.write_text(json.dumps({**now, "first_seen": first_seen}))
    build_system_prompt()
    return text


def _group(names: list[str]) -> str:
    """Collapse families like firecrawl-crawl, firecrawl-map into `firecrawl-*` (n)."""
    families: dict[str, list[str]] = {}
    for n in names:
        families.setdefault(n.split("-")[0], []).append(n)
    return ", ".join(f"`{k}-*` ({len(v)})" if len(v) > 2 else ", ".join(f"`{x}`" for x in v)
                     for k, v in families.items())


def generate_lite() -> str:
    return generate(refresh_mcps=False)


def build_system_prompt() -> None:
    base = (paths.PROFILE_DIR / "system-prompt.md").read_text()
    ctx = paths.CONTEXT_FILE.read_text() if paths.CONTEXT_FILE.exists() else ""
    paths.SYSTEM_PROMPT_FILE.write_text(base + "\n" + ctx)


def write_agent_files() -> None:
    """Profile files each agent run uses: MCP config and the sidebar's Claude settings."""
    paths.ensure_dirs()
    mcp = {"mcpServers": {"gecko": {"command": sys.executable, "args": ["-m", "geckos_helper", "mcp"]}}}
    paths.MCP_CONFIG_FILE.write_text(json.dumps(mcp, indent=2))
    profiles.write_readonly_mcp_config(sys.executable)
    if not paths.CLAUDE_SETTINGS.exists():
        paths.CLAUDE_SETTINGS.write_text((paths.PROFILE_DIR / "claude-settings.json").read_text())
    if not paths.SYSTEM_PROMPT_FILE.exists():
        build_system_prompt()

